"""Regenerate cloak_vector/vector/pb from the vendored .proto files.

The protos are Anki's Vector external interface (Apache-2.0), with the REST-gateway
annotations stripped so nothing beyond protobuf is needed. Run after editing a proto:
    pip install grpcio-tools && python scripts/gen_proto.py
"""
import pathlib
import re
import sys

from grpc_tools import protoc

root = pathlib.Path(__file__).resolve().parents[1]
src = root / "cloak_vector/vector/proto"
out = root / "cloak_vector/vector/pb"
out.mkdir(exist_ok=True)
for old in out.glob("*_pb2*.py"):
    old.unlink()

protos = sorted(str(p.name) for p in src.glob("*.proto"))
include = str(pathlib.Path(protoc.__file__).parent / "_proto")
rc = protoc.main(["protoc", f"-I{src}", f"-I{include}", f"--python_out={out}", f"--grpc_python_out={out}", *protos])
if rc:
    sys.exit(rc)

# generated code imports siblings absolutely (`import messages_pb2`); make them package-relative
for f in out.glob("*_pb2*.py"):
    f.write_text(re.sub(r"^import (\w+_pb2) as", r"from . import \1 as", f.read_text(), flags=re.M))
(out / "__init__.py").write_text('"""Generated by scripts/gen_proto.py. Do not edit."""\n')
print(f"generated {len(protos)} protos -> {out.relative_to(root)}")
